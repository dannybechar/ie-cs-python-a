"""Extract text from the ministry Python-A program (docx/pptx) into markdown + a manifest.

Usage:  python -I tools/ministry-import/extract.py <source_dir> <out_dir>

Dependency-free (zipfile + xml). Source files are only read, never executed.
Writes <out_dir>/extracts/*.md and <out_dir>/manifest.json.
"""
import hashlib
import json
import re
import sys
import zipfile
import xml.etree.ElementTree as ET
from pathlib import Path

NS = {
    "a": "http://schemas.openxmlformats.org/drawingml/2006/main",
    "p": "http://schemas.openxmlformats.org/presentationml/2006/main",
    "w": "http://schemas.openxmlformats.org/wordprocessingml/2006/main",
}
W = "{%s}" % NS["w"]


def docx_text(path):
    with zipfile.ZipFile(path) as z:
        root = ET.fromstring(z.read("word/document.xml"))
    out = []
    for p in root.iter(W + "p"):
        text = "".join(t.text or "" for t in p.iter(W + "t"))
        if not text.strip():
            continue
        style = p.find("w:pPr/w:pStyle", NS)
        sv = style.get(W + "val", "") if style is not None else ""
        if p.find("w:pPr/w:numPr", NS) is not None:
            text = "- " + text
        elif sv.lower().startswith("heading"):
            text = "## " + text
        out.append(text)
    return "\n\n".join(out)


def slide_paragraphs(xml_bytes):
    root = ET.fromstring(xml_bytes)
    return ["".join(t.text or "" for t in p.iter("{%s}t" % NS["a"])) for p in root.iter("{%s}p" % NS["a"])]


def pptx_text(path):
    with zipfile.ZipFile(path) as z:
        names = z.namelist()
        slides = sorted((n for n in names if re.fullmatch(r"ppt/slides/slide\d+\.xml", n)),
                        key=lambda n: int(re.findall(r"\d+", n)[-1]))
        out, images = [], 0
        for n in slides:
            idx = re.findall(r"\d+", n)[-1]
            body = [t for t in slide_paragraphs(z.read(n)) if t.strip()]
            notes_name = "ppt/notesSlides/notesSlide%s.xml" % idx
            notes = [t for t in slide_paragraphs(z.read(notes_name)) if t.strip()] if notes_name in names else []
            # drop the notes-slide slide-number placeholder (a bare digit)
            notes = [t for t in notes if not t.strip().isdigit()]
            out.append("### Slide %s\n\n%s" % (idx, "\n".join("- " + t for t in body) or "_(no text)_"))
            if notes:
                out.append("**Notes:**\n\n" + "\n".join("- " + t for t in notes))
        images = sum(1 for n in names if n.startswith("ppt/media/"))
    return "\n\n".join(out), len(slides), images


def main(src, dst):
    src, dst = Path(src), Path(dst)
    (dst / "extracts").mkdir(parents=True, exist_ok=True)
    manifest = []
    for f in sorted(src.rglob("*")):
        if not f.is_file():
            continue
        rel = f.relative_to(src)
        row = {
            "source": rel.as_posix(),
            "area": rel.parts[0] if len(rel.parts) > 1 else "(root)",
            "folder": rel.parts[1] if len(rel.parts) > 2 else "",
            "name": f.name,
            "ext": f.suffix.lower(),
            "sha1": hashlib.sha1(f.read_bytes()).hexdigest()[:12],
        }
        text, extra = "", {}
        try:
            if row["ext"] == ".docx":
                text = docx_text(f)
            elif row["ext"] == ".pptx":
                text, extra["slides"], extra["media"] = pptx_text(f)
            elif row["ext"] == ".md":
                text = f.read_text(encoding="utf-8")
        except Exception as e:  # report, keep going
            row["error"] = repr(e)
        row.update(extra)
        row["chars"] = len(text)
        row["status"] = "error" if "error" in row else ("image-only" if row["chars"] < 40 * max(extra.get("slides", 1), 1) and row["ext"] == ".pptx" else ("ok" if text.strip() else "empty"))
        if text.strip():
            m = re.match(r"\s*(\d+)(?:\.(\d+))?", row["folder"] or row["name"])
            key = ("m%02d" % int(m.group(1)) + ("-%s" % m.group(2) if m.group(2) else "")) if m else "misc"
            out_name = "%s-%s-%s.md" % (row["area"].strip("()").lower(), key, row["sha1"][:6])
            (dst / "extracts" / out_name).write_text(
                "# %s\n\nSource: `%s`\n\n%s\n" % (row["name"], row["source"], text), encoding="utf-8")
            row["extract"] = "extracts/" + out_name
        manifest.append(row)
    (dst / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding="utf-8")
    lines = ["# Manifest of the ministry Python-A program", "",
             "Generated by `tools/ministry-import/extract.py`. Folder number is authoritative; internal numbers in file names are not.", "",
             "| Area | Folder | File | Type | Slides | Chars | Status | Extract |", "|---|---|---|---|---|---|---|---|"]
    for r in manifest:
        lines.append("| %s | %s | %s | %s | %s | %d | %s | %s |" % (
            r["area"], r["folder"], r["name"].replace("|", "/"), r["ext"][1:], r.get("slides", ""), r["chars"], r["status"], r.get("extract", "")))
    (dst / "manifest.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("files:", len(manifest), "| by status:",
          {s: sum(1 for r in manifest if r["status"] == s) for s in sorted({r["status"] for r in manifest})})


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
