# Pen practice - one function for each task
import turtle

turtle.Screen()
turtle.shape("turtle")


# Warm-up: two lines with a gap
def warm_up():
    turtle.forward(60)
    turtle.penup()
    turtle.forward(40)
    turtle.pendown()
    turtle.forward(60)


# Write each new task as a function above this line.

# Run ONE task at a time. Keep the other calls as comments.
warm_up()

turtle.done()
